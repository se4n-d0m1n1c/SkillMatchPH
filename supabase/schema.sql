-- Every new Auth user receives a student profile. Role is deliberately hard-coded:
-- user-editable Auth metadata must never be allowed to create an administrator.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  provided_username text := nullif(lower(trim(new.raw_user_meta_data ->> 'username')), '');
  provided_student_no text := nullif(trim(new.raw_user_meta_data ->> 'student_no'), '');
begin
  if provided_username is not null and exists (
    select 1 from public.profiles where lower(username) = provided_username
  ) then
    raise exception 'That username is unavailable. Choose another username.';
  end if;

  if provided_student_no is not null and exists (
    select 1 from public.profiles where lower(student_no) = lower(provided_student_no)
  ) then
    raise exception 'That student number is already in use.';
  end if;

  insert into public.profiles (
    id, username, first_name, last_name, student_no, grade_level, shs_track, shs_strand, role, status
  ) values (
    new.id,
    provided_username,
    coalesce(new.raw_user_meta_data ->> 'first_name', ''),
    coalesce(new.raw_user_meta_data ->> 'last_name', ''),
    coalesce(provided_student_no, new.id::text),
    coalesce(nullif(new.raw_user_meta_data ->> 'grade_level', '')::smallint, 11),
    coalesce(new.raw_user_meta_data ->> 'shs_track', 'Academic'),
    coalesce(new.raw_user_meta_data ->> 'shs_strand', 'STEM'),
    'student',
    'pending'
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Security helper. SECURITY DEFINER avoids circular RLS checks on profiles.
create function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.admin_notifications enable row level security;
alter table public.admin_contact_requests enable row level security;
alter table public.programs enable row level security;
alter table public.universities enable row level security;
alter table public.program_universities enable row level security;

-- Students can view their own profile; admins can manage all profiles.
create policy "read own profile or all as admin" on public.profiles
  for select to authenticated using (id = auth.uid() or public.is_admin());
create policy "admin updates profiles" on public.profiles
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "students update own profile" on public.profiles
  for update to authenticated
  using (id = auth.uid() and role = 'student')
  with check (id = auth.uid() and role = 'student');
create policy "admins read notifications" on public.admin_notifications
  for select to authenticated using (public.is_admin());
create policy "admins read contact requests" on public.admin_contact_requests
  for select to authenticated using (public.is_admin());

-- Self-service edits must never change authorization or approval fields.
create function public.protect_profile_system_fields()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if not public.is_admin() then
    new.id := old.id;
    new.role := old.role;
    new.status := old.status;
    if current_setting('app.allow_username_change', true) is distinct from 'true' then
      new.username := old.username;
      new.username_changed_at := old.username_changed_at;
    end if;
    new.created_at := old.created_at;
  end if;
  return new;
end;
$$;

create trigger profiles_protect_system_fields before update on public.profiles
for each row execute function public.protect_profile_system_fields();

create function public.notify_admins_of_student_profile_update()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  fields text[];
begin
  if old.role = 'student' and auth.uid() = old.id then
    fields := array_remove(array[
      case when new.first_name is distinct from old.first_name then 'first name' end,
      case when new.last_name is distinct from old.last_name then 'last name' end,
      case when new.student_no is distinct from old.student_no then 'student number' end,
      case when new.grade_level is distinct from old.grade_level then 'grade level' end,
      case when new.shs_track is distinct from old.shs_track then 'SHS track' end,
      case when new.shs_strand is distinct from old.shs_strand then 'SHS strand' end,
      case when new.avatar_path is distinct from old.avatar_path then 'profile picture' end
    ], null);

    if cardinality(fields) > 0 then
      insert into public.admin_notifications (type, student_id, changed_fields)
      values ('student_profile_updated', old.id, fields);
    end if;
  end if;
  return new;
end;
$$;

create trigger profiles_notify_admins_after_student_update
  after update on public.profiles
  for each row execute function public.notify_admins_of_student_profile_update();

create function public.notify_admins_of_student_registration()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if new.role = 'student' then
    insert into public.admin_notifications (type, student_id)
    values ('student_registration', new.id);
  end if;
  return new;
end;
$$;

create trigger profiles_notify_admins_after_student_insert
  after insert on public.profiles
  for each row execute function public.notify_admins_of_student_registration();

