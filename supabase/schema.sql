-- Public login-page request. Unknown emails intentionally receive the same response.
create function public.request_admin_contact(submitted_email text)
returns void
language plpgsql
security definer set search_path = public, auth
as $$
declare
  normalized_email text := lower(trim(coalesce(submitted_email, '')));
  matched_profile_id uuid;
begin
  if length(normalized_email) < 3 or length(normalized_email) > 320 then
    raise exception 'Enter a valid username or email address';
  end if;

  if normalized_email like '%@%' then
    select profile.id into matched_profile_id
    from auth.users account
    join public.profiles profile on profile.id = account.id
    where lower(account.email) = normalized_email
    limit 1;
  else
    select profile.id into matched_profile_id
    from public.profiles profile
    where lower(profile.username) = normalized_email
    limit 1;

    if matched_profile_id is not null then
      select lower(account.email) into normalized_email
      from auth.users account
      where account.id = matched_profile_id;
    end if;
  end if;

  if matched_profile_id is not null then
    insert into public.admin_contact_requests (profile_id, requester_email)
    values (matched_profile_id, normalized_email)
    on conflict (profile_id) where status = 'open' do nothing;

    if found then
      insert into public.admin_notifications (type, student_id)
      values ('admin_contact_requested', matched_profile_id);
    end if;
  end if;
end;
$$;

create function public.resolve_admin_contact_request(target_request_id uuid)
returns void
language plpgsql
security definer set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Only administrators can resolve contact requests';
  end if;

  update public.admin_contact_requests
  set status = 'resolved', resolved_at = now(), resolved_by = auth.uid()
  where id = target_request_id and status = 'open';
end;
$$;

revoke all on function public.request_admin_contact(text) from public;
revoke all on function public.resolve_admin_contact_request(uuid) from public;
grant execute on function public.request_admin_contact(text) to anon, authenticated;
grant execute on function public.resolve_admin_contact_request(uuid) to authenticated;
alter publication supabase_realtime add table public.admin_contact_requests;

create function public.update_own_admin_username(requested_username text)
returns text
language plpgsql
security definer set search_path = public
as $$
declare
  normalized_username text := lower(trim(coalesce(requested_username, '')));
begin
  if not public.is_admin() then
    raise exception 'Only administrators can update an administrator username';
  end if;
  if normalized_username !~ '^[a-z0-9][a-z0-9._-]{2,29}$' then
    raise exception 'Username must be 3-30 characters and use only letters, numbers, dots, underscores, or hyphens';
  end if;
  update public.profiles set username = normalized_username
  where id = auth.uid() and role = 'admin';
  return normalized_username;
exception when unique_violation then
  raise exception 'That username is already in use';
end;
$$;

revoke all on function public.update_own_admin_username(text) from public;
grant execute on function public.update_own_admin_username(text) to authenticated;

create function public.update_student_username(target_student_id uuid, requested_username text)
returns text
language plpgsql
security definer set search_path = public
as $$
declare
  normalized_username text := lower(trim(coalesce(requested_username, '')));
begin
  if not public.is_admin() then
    raise exception 'Only administrators can update student usernames';
  end if;
  if normalized_username !~ '^[a-z0-9][a-z0-9._-]{2,29}$' then
    raise exception 'Username must be 3-30 characters and use only letters, numbers, dots, underscores, or hyphens';
  end if;
  if not exists (select 1 from public.profiles where id = target_student_id and role = 'student') then
    raise exception 'Student account not found';
  end if;
  update public.profiles set username = normalized_username
  where id = target_student_id and role = 'student';
  return normalized_username;
exception when unique_violation then
  raise exception 'That username is already in use';
end;
$$;

revoke all on function public.update_student_username(uuid, text) from public;
grant execute on function public.update_student_username(uuid, text) to authenticated;

-- Used by the Admin > Student Management delete action. It also removes auth.users.
create function public.delete_student(target_user_id uuid)
returns void
language plpgsql
security definer set search_path = public, auth
as $$
begin
  if not public.is_admin() then
    raise exception 'Only administrators can delete student accounts';
  end if;

  if target_user_id = auth.uid() then
    raise exception 'Administrators cannot delete their own account';
  end if;

  if not exists (
    select 1 from public.profiles
    where id = target_user_id and role = 'student'
  ) then
    raise exception 'Student not found';
  end if;

  delete from auth.users where id = target_user_id;
end;
$$;

revoke all on function public.delete_student(uuid) from public;
grant execute on function public.delete_student(uuid) to authenticated;

