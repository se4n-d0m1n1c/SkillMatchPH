-- SkillMatchPH database schema
-- Run this file in the Supabase SQL Editor of a new project.
-- Authentication users live in Supabase's managed auth.users table.
-- To load the starter university catalog afterwards, run
-- supabase/seed_top_ph_universities.sql.

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  first_name text not null,
  last_name text not null,
  student_no text not null unique,
  grade_level smallint not null check (grade_level in (11, 12)),
  shs_track text not null,
  shs_strand text not null,
  avatar_path text,
  username text not null unique check (username ~ '^[a-z0-9][a-z0-9._-]{2,29}$'),
  username_changed_at timestamptz,
  role text not null default 'student' check (role in ('student', 'admin')),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.programs (
  id uuid primary key default gen_random_uuid(),
  title text not null unique,
  category text not null check (category in (
    'Technology', 'Business', 'Engineering', 'Health',
    'Arts & Humanities', 'Sciences', 'Education'
  )),
  description text not null,
  icon_name text not null default 'BookOpen',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.universities (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  location text,
  website text,
  logo_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- A university can offer many programs, and a program can be offered by many universities.
create table public.program_universities (
  program_id uuid not null references public.programs(id) on delete cascade,
  university_id uuid not null references public.universities(id) on delete cascade,
  primary key (program_id, university_id)
);

create table public.admin_contact_requests (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  requester_email text not null,
  reason text not null default 'password_help' check (reason in ('password_help')),
  status text not null default 'open' check (status in ('open', 'resolved')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid references public.profiles(id) on delete set null
);

create table public.admin_notifications (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('student_registration', 'student_profile_updated', 'admin_contact_requested', 'student_username_changed')),
  student_id uuid not null references public.profiles(id) on delete cascade,
  changed_fields text[] not null default '{}',
  created_at timestamptz not null default now()
);

create index profiles_role_status_idx on public.profiles (role, status);
create index program_universities_university_id_idx on public.program_universities (university_id);
create index admin_notifications_created_at_idx on public.admin_notifications (created_at desc);
create unique index admin_contact_requests_one_open_per_profile_idx
  on public.admin_contact_requests (profile_id) where status = 'open';
create index admin_contact_requests_status_created_idx
  on public.admin_contact_requests (status, created_at desc);

